const CORRECT_LINES = ['做得好，這一步完成了。', '沒錯，就是這樣。', '很好，這樣下次也找得到。'];

export const DIALOGUES = [];

for (const level of [1, 2, 3, 4, 5, 6]) {
  const [enter, stuck, done] = LEVEL_LINES[level];
  DIALOGUES.push(line(level, null, 'enter', 'client', 'explain', `「${enter}」`, { position: 'top-right' }));
  DIALOGUES.push(line(level, null, 'stuck', 'helper', 'remind', stuck));
  DIALOGUES.push(line(level, null, 'complete', 'guide', 'success', done));
  DIALOGUES.push(line(level, null, 'deliver', 'client', 'success', CLIENT_DELIVER[level], { position: 'top-right' }));
  STEP_LINES[level].forEach(([concept, h1, h2], step) => {
    DIALOGUES.push(line(level, step, 'concept', 'guide', 'explain', concept));
    DIALOGUES.push(line(level, step, 'hint', 'helper', 'remind', h1, { hintLevel: 1 }));
    // 第六關不主動給完整解答：第二層提示仍只提醒方向
    DIALOGUES.push(line(level, step, 'hint', 'helper', level === 6 ? 'remind' : 'explain', h2, { hintLevel: 2 }));
    DIALOGUES.push(line(level, step, 'correct', 'guide', 'encourage', CORRECT_LINES[step % CORRECT_LINES.length]));
    DIALOGUES.push(line(level, step, 'wrong', 'guide', 'puzzled', '有一處還不對，看看標紅的地方。'));
  });
}

export const IDLE_HINT_MS = 20000;

export function findLine(level, step, trigger, hintLevel = 0) {
  return DIALOGUES.find(d => d.level === level && d.step === step && d.trigger === trigger && d.hintLevel === hintLevel)
    || DIALOGUES.find(d => d.level === level && d.step === null && d.trigger === trigger);
}
